"""Per-country table of the satellite-change (seam) tests, from the web export (same numbers as the app).

    python scripts/seam_table.py        # -> docs/seam_table.md and docs/seam_table.csv

For each country: the step at the 2012 switch to VIIRS when the satellites are joined as they are, the same
step after harmonization, and for each satellite change (2002 Aqua joins, 2012 VIIRS, 2018 NOAA-20) the share
of ordinary year-to-year steps (placebo dates, no satellite change) that are smaller. A change counts as
unusual at >= 0.95, as in the app (web/src/features/area-summary/lib/consistency.ts).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
UNUSUAL = 0.95
SEAMS = {"2002": "Aqua joins (2002)", "2012": "VIIRS (2012)", "2018": "NOAA-20 (2018)"}


def seam_rows(index: dict, data: Path) -> pd.DataFrame:
    rows = []
    for a in index["areas"]:
        if a["level"] not in ("asia", "country") or a.get("empty"):
            continue
        p = data / "detail" / f"{a['id'] or '_all'}.json"
        if not p.exists():
            continue
        s = json.loads(p.read_text(encoding="utf-8"))["seams"]
        r = {"id": a["id"] or "asia", "name": a["name"], "naive2012": s.get("naiveStep2012")}
        for x in s["rows"]:
            k = x["seam"][:4]
            r[f"step{k}"] = x["stepPct"]
            r[f"placebo{k}"] = x["placebo"]
        rows.append(r)
    return pd.DataFrame(rows)


def area_summary(index: dict, data: Path) -> tuple[int, int]:
    """(ordinary, tested) seam tests over every exported area file."""
    ok = n = 0
    for a in index["areas"]:
        p = data / "detail" / f"{a['id'] or '_all'}.json"
        if a.get("empty") or not p.exists():
            continue
        for x in json.loads(p.read_text(encoding="utf-8"))["seams"]["rows"]:
            if x["placebo"] is not None:
                n += 1
                ok += x["placebo"] < UNUSUAL
    return ok, n


def fmt(v, pct=True):
    if v is None or pd.isna(v):
        return "–"
    return f"{v:+.0f} %" if pct else f"{v:.2f}"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", type=Path, default=ROOT / "web" / "public" / "data")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "seam_table.md")
    args = ap.parse_args(argv)
    index = json.loads((args.data / "index.json").read_text(encoding="utf-8"))
    t = seam_rows(index, args.data)
    t.to_csv(args.out.with_suffix(".csv"), index=False)
    ok, n = area_summary(index, args.data)
    countries = t[t["id"] != "asia"].sort_values("name")
    head = t[t["id"] == "asia"]
    lines = ["# Satellite-change tests per country", "",
             "Generated by `scripts/seam_table.py` from the web export (same numbers as the app). "
             "**Step** = fire 2 years after vs 2 years before the switch, seasons removed. **Ordinary** = share of "
             f"year-to-year steps at dates with no satellite change that are smaller; a change is flagged at ≥ {UNUSUAL}.", "",
             f"Over every exported area (Asia, regions, countries, provinces, districts): **{ok} of {n}** satellite "
             "changes look like ordinary year-to-year change.", "",
             "| Area | 2012 step, joined as they are | 2012 step, harmonized | Ordinary? 2002 · 2012 · 2018 |",
             "|---|---:|---:|---|"]
    for _, r in pd.concat([head, countries]).iterrows():
        marks = []
        for k in ("2002", "2012", "2018"):
            v = r.get(f"placebo{k}")
            marks.append("–" if v is None or pd.isna(v) else ("yes" if v < UNUSUAL else f"**flag** ({v:.2f})"))
        name = f"**{r['name']}**" if r["id"] in ("asia", "arg") else r["name"]
        lines.append(f"| {name} | {fmt(r['naive2012'])} | {fmt(r.get('step2012'))} | {' · '.join(marks)} |")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    flagged = int((countries[[c for c in countries if c.startswith("placebo")]] >= UNUSUAL).any(axis=1).sum())
    print(f"{len(countries)} countries, {flagged} with a flagged change; all areas: {ok} of {n} ordinary -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
